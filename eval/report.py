from datetime import datetime
from typing import Optional


def generate_eval_report(results: dict, output_path: Optional[str] = None) -> str:
    """
    Generate a markdown evaluation report.
    
    Args:
        results: Evaluation results from Evaluator.run_full_evaluation()
        output_path: Optional path to save the report
        
    Returns:
        Markdown report string
    """
    summary = results.get("summary", {})
    retrieval = results.get("retrieval", {})
    generation = results.get("generation", {})
    security = results.get("security", {})
    by_category = results.get("by_category", {})
    
    report = f"""# Vault Evaluation Report

Generated: {datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")}

---

## Summary

| Metric | Value |
|--------|-------|
| Total Questions | {summary.get("total_questions", 0)} |
| Successful | {summary.get("successful", 0)} |
| Errors | {summary.get("errors", 0)} |
| Avg Latency | {summary.get("avg_latency_ms", 0):.0f}ms |

---

## Retrieval Quality

| Metric | Score | Target | Status |
|--------|-------|--------|--------|
| Precision@5 | {retrieval.get("precision_at_5", 0):.3f} | ≥ 0.85 | {"✓" if retrieval.get("precision_at_5", 0) >= 0.85 else "✗"} |
| Recall@k | {retrieval.get("recall_at_k", 0):.3f} | ≥ 0.90 | {"✓" if retrieval.get("recall_at_k", 0) >= 0.90 else "✗"} |
| MRR | {retrieval.get("mrr", 0):.3f} | ≥ 0.80 | {"✓" if retrieval.get("mrr", 0) >= 0.80 else "✗"} |

---

## Generation Quality

| Metric | Score | Target | Status |
|--------|-------|--------|--------|
| Faithfulness | {generation.get("faithfulness", 0):.3f} | ≥ 0.90 | {"✓" if generation.get("faithfulness", 0) >= 0.90 else "✗"} |
| Relevance | {generation.get("relevance", 0):.3f} | ≥ 0.85 | {"✓" if generation.get("relevance", 0) >= 0.85 else "✗"} |
| Citation Accuracy | {generation.get("citation_accuracy", 0):.3f} | ≥ 0.95 | {"✓" if generation.get("citation_accuracy", 0) >= 0.95 else "✗"} |

---

## Security (NON-NEGOTIABLE)

| Metric | Value | Target | Status |
|--------|-------|--------|--------|
| **Unauthorized Leakage Rate** | **{security.get("unauthorized_leakage_rate", 0):.3f}** | **0.0** | {"✓" if security.get("unauthorized_leakage_rate", 0) == 0.0 else "✗ CRITICAL"} |
| Permission Boundary Accuracy | {security.get("permission_boundary_accuracy", 0):.3f} | ≥ 0.98 | {"✓" if security.get("permission_boundary_accuracy", 0) >= 0.98 else "✗"} |
| Total Leaks | {security.get("total_leaks", 0)} | 0 | {"✓" if security.get("total_leaks", 0) == 0 else "✗ CRITICAL"} |
| Correct Refusals | {security.get("total_refusals_correct", 0)}/{security.get("total_refusals_expected", 0)} | All | {"✓" if security.get("total_refusals_correct", 0) == security.get("total_refusals_expected", 0) else "✗"} |

---

## Performance by Category

"""
    
    for cat, metrics in by_category.items():
        report += f"""### {cat.replace("_", " ").title()}

| Metric | Score |
|--------|-------|
| Questions | {metrics.get("count", 0)} |
| Avg Relevance | {metrics.get("avg_relevance", 0):.3f} |
| Avg Faithfulness | {metrics.get("avg_faithfulness", 0):.3f} |

"""
    
    report += """---

## Overall Verdict

"""
    
    # Calculate overall pass/fail
    all_pass = True
    
    if retrieval.get("precision_at_5", 0) < 0.85:
        all_pass = False
        report += "- ✗ Retrieval Precision@5 below target\n"
    
    if retrieval.get("recall_at_k", 0) < 0.90:
        all_pass = False
        report += "- ✗ Retrieval Recall@k below target\n"
    
    if generation.get("faithfulness", 0) < 0.90:
        all_pass = False
        report += "- ✗ Generation Faithfulness below target\n"
    
    if security.get("unauthorized_leakage_rate", 0) != 0.0:
        all_pass = False
        report += "- ✗ CRITICAL: Unauthorized content leakage detected\n"
    
    if all_pass:
        report += "### ✓ ALL CHECKS PASSED\n\n"
        report += "The system meets all quality and security targets.\n"
    else:
        report += "### ✗ SOME CHECKS FAILED\n\n"
        report += "Review the failing metrics above and address before production deployment.\n"
    
    report += "\n---\n\n*Report generated by Vault Evaluation Framework*\n"
    
    # Save to file if path provided
    if output_path:
        with open(output_path, "w") as f:
            f.write(report)
    
    return report
