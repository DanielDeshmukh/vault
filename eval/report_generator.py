
"""Generate a well-formatted markdown evaluation report.

Includes per-question details: query, role, answer, expected keywords,
latency, citations, and timestamps.
"""

from datetime import datetime
from typing import Optional

from eval.api_evaluator import QueryResult, print_evaluation_summary


def generate_report(
    results: list[QueryResult],
    output_path: Optional[str] = None,
) -> str:
    """Generate a comprehensive markdown evaluation report.

    Args:
        results: All query results from the evaluator.
        output_path: If provided, save the report to this file.

    Returns:
        The markdown report string.
    """
    summary = print_evaluation_summary(results)
    run_time = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")

    report = f"""# Vault Evaluation Report

**Generated:** {run_time}
**Total Queries:** {summary['total_queries']}
**Successful:** {summary['successful']}
**Errors:** {summary['errors']}
**Avg Latency:** {summary['avg_latency_ms']:.0f}ms
**Avg Relevance:** {summary['avg_relevance']:.2%}

---

## Summary by Role

| Role | Queries | Successful | Refused | Avg Relevance | Avg Latency |
|------|---------|------------|---------|---------------|-------------|
"""

    for role, data in summary["by_role"].items():
        report += (
            f"| {role} | {data['total']} | {data['successful']} | "
            f"{data['refused']} | {data['avg_relevance']:.2%} | "
            f"{data['avg_latency_ms']:.0f}ms |\n"
        )

    report += f"""
---

## Summary by Category

| Category | Queries | Successful | Avg Relevance |
|----------|---------|------------|---------------|
"""

    for cat, data in summary["by_category"].items():
        report += (
            f"| {cat.replace('_', ' ').title()} | {data['total']} | "
            f"{data['successful']} | {data['avg_relevance']:.2%} |\n"
        )

    report += """
---

## Per-Question Details

"""

    # Group results by question for detailed view
    by_question: dict[str, list[QueryResult]] = {}
    for r in results:
        by_question.setdefault(r.question_id, []).append(r)

    for qid, q_results in by_question.items():
        q = q_results[0]
        report += f"""### {qid}: {q.question}

**Category:** {q.category.replace('_', ' ').title()}

"""

        for r in q_results:
            status = "✅" if r.success else "❌"
            refused_marker = " (refused)" if r.refused else ""
            report += f"""#### {r.role}{refused_marker}

| Field | Value |
|-------|-------|
| Status | {status} {'Success' if r.success else 'Error'} |
| Latency | {r.latency_ms:.0f}ms |
| Relevance | {r.relevance_score:.2%} |
| Citations | {r.citation_count} |
| Timestamp | {r.timestamp} |

**Answer:**
```
{r.answer[:500]}{'...' if len(r.answer) > 500 else ''}
```

"""
            if r.citations:
                report += "**Citations:**\n"
                for i, c in enumerate(r.citations[:5], 1):
                    title = c.get("title", "N/A")
                    doc_id = c.get("document_id", "N/A")
                    score = c.get("score", 0)
                    report += f"{i}. `{doc_id}` — {title} (score: {score:.4f})\n"
                if len(r.citations) > 5:
                    report += f"... and {len(r.citations) - 5} more\n"
                report += "\n"

            if r.error:
                report += f"**Error:** {r.error}\n\n"

        report += "---\n\n"

    report += f"""*Report generated by Vault Evaluation Framework*
"""

    if output_path:
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(report)
        print(f"Report saved to: {output_path}")

    return report
